def calculate_scavenging_efficiency(rain_mm, humidity):
    # E: Collection efficiency (0 to 1)
    # R: Rain rate (mm/hr)
    # Dd: Median droplet diameter (m)
    E = 0.7
    R = rain_mm
    Dd = 0.002 # 2mm average natural raindrop

    if R == 0:
        return 0

    # Lambda calculation (Simplified)
    lam = (3 * E * R) / (2 * Dd)

    # Humidity Adjustment: High humidity increases particle size, making them easier to catch
    humidity_factor = 1 + (humidity / 100)
    return lam * humidity_factor

