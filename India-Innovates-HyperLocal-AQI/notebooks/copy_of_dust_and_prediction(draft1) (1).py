    # Cluster 2: Residential (Lower baseline)
    kmeans = KMeans(n_clusters=3, random_state=42)
    pivot_df['Cluster'] = kmeans.fit_predict(pivot_df)

    # 3. Decision Logic for "Shield Formation"
    def determine_shield_priority(row):
        if row['Cluster'] == 0: return "Active Interceptor (Perimeter)"
        if row['Cluster'] == 1: return "Mobile Unit (Traffic Support)"
        return "Residential Guard (Deep Protection)"

    pivot_df['Shield_Role'] = pivot_df.apply(determine_shield_priority, axis=1)

    # 4. Visualize the Behavioral DNA
