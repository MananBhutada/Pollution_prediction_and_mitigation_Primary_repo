AIR_VISCOSITY = 1.81e-5  # kg/(m*s)
WATER_DENSITY = 1000     # kg/m3
GRAVITY = 9.81           # m/s2

def calculate_residency(height, droplet_diameter_um):
    # Convert microns to meters
    d = droplet_diameter_um * 1e-6
    # Stokes' Law for Terminal Velocity (V = (rho * g * d^2) / (18 * mu))
    v_terminal = (WATER_DENSITY * GRAVITY * d**2) / (18 * AIR_VISCOSITY)
    # Time = Distance / Speed
    residency_time = height / v_terminal
    return v_terminal, residency_time

