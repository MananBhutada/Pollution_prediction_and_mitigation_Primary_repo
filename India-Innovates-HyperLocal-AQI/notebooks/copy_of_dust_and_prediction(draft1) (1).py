p_y = np.random.uniform(10, 90, NUM_PEOPLE)
p_z = np.random.choice([0, 5, 12, 20], NUM_PEOPLE, p=[0.7, 0.1, 0.1, 0.1])

# Initialize Dust Levels (Starts clean)
current_dust = np.zeros(NUM_PEOPLE)

# --- PHYSICS ENGINE ---
def update_physics(frame):
    global current_dust

    # 1. EMISSION PHASE (Frames 0-40)
    # Dust is continuously emitted from the epicenter
    if frame < 40:
        # Calculate distance from epicenter
        dist_sq = (p_x - 50)**2 + (p_y - 50)**2 + (p_z)**2
        # Add new dust inversely proportional to distance
        new_dust = 100 * np.exp(-0.005 * dist_sq)
        current_dust += new_dust * 0.5 # Accumulation rate

    # 2. ADVECTION PHASE (Frames 10-100)
    # Wind pushes the dust vectorially
    if frame > 10:
        # Shift dust based on wind vector (Simple advection simulation)
        # We simulate this by biasing the decay: upwind decays fast, downwind stays

        # Vector from center to person
        rel_x = p_x - 50
        rel_y = p_y - 50

        # Dot product to find downwind alignment
        alignment = (rel_x * WIND_VEC[0] + rel_y * WIND_VEC[1])

        # Decay factor: High decay if upwind (alignment < 0), Low decay if downwind
        decay = np.where(alignment < 0, 0.90, 0.98)
        current_dust *= decay

    # 3. MITIGATION PHASE (Frames 50-100)
    # AI System activates
    is_mitigating = frame >= 50
    if is_mitigating:
        # Calculate geometric targets
        dist_to_center = np.sqrt((p_x - 50)**2 + (p_y - 50)**2)

        # Check if point is Downwind
        rel_x = p_x - 50
        rel_y = p_y - 50
        dot_prod = rel_x * WIND_VEC[0] + rel_y * WIND_VEC[1]

        # Target Mask: Inside Radius AND Downwind
        target_mask = (dist_to_center < SPRAY_RADIUS) & (dot_prod > -5)

        # Apply Washout
        # Efficiency increases over time (as mist saturates air)
        washout_factor = 1 - (WASHOUT_EFFICIENCY * ((frame - 50) / 50))
        current_dust[target_mask] *= washout_factor

    return current_dust, is_mitigating

