    # 3. Simulate Dust Diffusion (Simplified Gaussian)
    # Distance of each person from the dust source
    distances = np.linalg.norm(people - epicenter, axis=1)
    base_dust = 500 / (distances + 1) # PM10 concentration decays with distance

    # 4. Mitigation Logic (The Sprayer)
    washout_efficiency = 0.85 # 85% dust reduction
    sprayer_range = 30 # meters

    mitigated_dust = base_dust.copy()
    mud_points = []

